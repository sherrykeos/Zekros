const Player = require("./Player");

const ROOM_STATUS = Object.freeze({
  WAITING: "WAITING",
  READY: "READY",
  PLAYING: "PLAYING",
  FINISHED: "FINISHED",
  CLOSED: "CLOSED",
});

const DEFAULT_SETTINGS = Object.freeze({
  maxPlayers: 2,
  allowSpectators: true,
  isPrivate: false,
});

/**
 * Room is a multiplayer lobby. It holds references to players, spectators, and
 * matches, but leaves all identity generation, game rules, and persistence to
 * outer layers.
 */
class Room {
  /**
   * @param {object} options Room creation options.
   * @param {string} options.id Stable room id generated by RoomManager.
   * @param {string} options.code Human-friendly join code generated by RoomManager.
   * @param {Player|object|null} [options.host] Host player reference.
   * @param {Array<Player|object>} [options.players] Current room players.
   * @param {Array<Player|object>} [options.spectators] Future-ready spectators.
   * @param {object|null} [options.currentMatch] Current Match reference.
   * @param {Array<object>} [options.matches] Match references hosted over time.
   * @param {string} [options.status] Current room lifecycle status.
   * @param {string|Date} [options.createdAt] Room creation time.
   * @param {object} [options.settings] Room settings such as maxPlayers.
   * @param {object} [options.metadata] Optional future-safe room metadata.
   */
  constructor({
    id,
    code,
    host = null,
    players = [],
    spectators = [],
    currentMatch = null,
    matches = [],
    status = ROOM_STATUS.WAITING,
    createdAt = new Date(),
    settings = {},
    metadata = {},
  } = {}) {
    if (!id || !code) {
      throw new Error("Room requires id and code generated by RoomManager.");
    }

    this.id = id;
    this.code = code;
    this.host = host ? this.normalizePlayer(host) : null;
    this.players = [];
    this.spectators = [];
    this.currentMatch = currentMatch;
    this.matches = [...matches];
    this.status = status;
    this.createdAt = this.toIsoString(createdAt);
    this.settings = { ...DEFAULT_SETTINGS, ...settings };
    this.metadata = this.clone(metadata);

    if (this.host) {
      this.addPlayer(this.host);
    }

    for (const player of players) {
      this.addPlayer(player);
    }

    for (const spectator of spectators) {
      this.addSpectator(spectator);
    }
  }

  /**
   * Adds a player to the playable seats without assigning game rules here.
   *
   * @param {Player|object} player Player instance or serializable player data.
   * @returns {Player|null} Added player, or null when room is full/duplicate.
   */
  addPlayer(player) {
    const normalizedPlayer = this.normalizePlayer(player);

    if (this.hasPlayer(normalizedPlayer.id) || this.isFull()) {
      return null;
    }

    this.players.push(normalizedPlayer);

    if (!this.host) {
      this.host = normalizedPlayer;
    }

    this.refreshReadinessStatus();

    return normalizedPlayer;
  }

  /**
   * Removes a player by id and promotes the next player as host if needed.
   *
   * @param {string|Player|object} player Player id or player-like object.
   * @returns {Player|null} Removed player, or null when not found.
   */
  removePlayer(player) {
    const playerId = this.getEntityId(player);
    const index = this.players.findIndex((entry) => entry.id === playerId);

    if (index === -1) {
      return null;
    }

    const [removedPlayer] = this.players.splice(index, 1);

    if (this.host?.id === removedPlayer.id) {
      this.host = this.players[0] ?? null;
    }

    this.refreshReadinessStatus();

    return removedPlayer;
  }

  /**
   * Adds a spectator without consuming a playable seat.
   *
   * @param {Player|object} spectator Spectator player reference/data.
   * @returns {Player|null} Added spectator, or null if disabled/duplicate.
   */
  addSpectator(spectator) {
    if (!this.settings.allowSpectators) {
      return null;
    }

    const normalizedSpectator = this.normalizePlayer(spectator);

    if (this.hasSpectator(normalizedSpectator.id) || this.hasPlayer(normalizedSpectator.id)) {
      return null;
    }

    this.spectators.push(normalizedSpectator);

    return normalizedSpectator;
  }

  /**
   * Removes a spectator by id.
   *
   * @param {string|Player|object} spectator Spectator id or player-like object.
   * @returns {Player|null} Removed spectator, or null when not found.
   */
  removeSpectator(spectator) {
    const spectatorId = this.getEntityId(spectator);
    const index = this.spectators.findIndex((entry) => entry.id === spectatorId);

    if (index === -1) {
      return null;
    }

    const [removedSpectator] = this.spectators.splice(index, 1);
    return removedSpectator;
  }

  /**
   * @returns {boolean} True when all playable seats are occupied.
   */
  isFull() {
    return this.players.length >= this.settings.maxPlayers;
  }

  /**
   * Checks playable-seat membership without inspecting sockets or auth.
   *
   * @param {string|Player|object} player Player id or player-like object.
   * @returns {boolean} True when the player is in the room players list.
   */
  hasPlayer(player) {
    const playerId = this.getEntityId(player);
    return this.players.some((entry) => entry.id === playerId);
  }

  /**
   * Retrieves a player reference from the playable seats.
   *
   * @param {string|Player|object} player Player id or player-like object.
   * @returns {Player|null} Player reference or null.
   */
  getPlayer(player) {
    const playerId = this.getEntityId(player);
    return this.players.find((entry) => entry.id === playerId) ?? null;
  }

  /**
   * Checks spectator membership separately from playable seats.
   *
   * @param {string|Player|object} spectator Spectator id or player-like object.
   * @returns {boolean} True when the spectator is present.
   */
  hasSpectator(spectator) {
    const spectatorId = this.getEntityId(spectator);
    return this.spectators.some((entry) => entry.id === spectatorId);
  }

  /**
   * Stores the current Match reference and remembers it for rematch history.
   * Room does not inspect or manipulate Match internals.
   *
   * @param {object} match Match reference.
   */
  setCurrentMatch(match) {
    this.currentMatch = match;
    this.status = ROOM_STATUS.PLAYING;

    if (match && !this.matches.some((entry) => entry === match || entry.id === match.id)) {
      this.matches.push(match);
    }
  }

  /**
   * Clears the active match reference while preserving prior match references.
   */
  clearMatch() {
    this.currentMatch = null;
    this.status = this.players.length > 0 ? ROOM_STATUS.WAITING : ROOM_STATUS.CLOSED;
  }

  /**
   * Closes the room for future manager cleanup without deleting runtime data.
   */
  close() {
    this.status = ROOM_STATUS.CLOSED;
    this.currentMatch = null;
  }

  /**
   * @returns {object} Serializable room state for managers, APIs, or sockets.
   */
  getState() {
    return {
      id: this.id,
      code: this.code,
      host: this.host ? this.host.toJSON() : null,
      players: this.players.map((player) => player.toJSON()),
      spectators: this.spectators.map((spectator) => spectator.toJSON()),
      currentMatchId: this.currentMatch?.id ?? null,
      matchIds: this.matches.map((match) => match.id).filter(Boolean),
      status: this.status,
      createdAt: this.createdAt,
      settings: this.clone(this.settings),
      metadata: this.clone(this.metadata),
    };
  }

  normalizePlayer(player) {
    return player instanceof Player ? player : new Player(player);
  }

  getEntityId(entity) {
    return typeof entity === "string" ? entity : entity?.id;
  }

  refreshReadinessStatus() {
    if (this.status === ROOM_STATUS.PLAYING || this.status === ROOM_STATUS.CLOSED) {
      return;
    }

    this.status = this.isFull() ? ROOM_STATUS.READY : ROOM_STATUS.WAITING;
  }

  toIsoString(value) {
    return value instanceof Date ? value.toISOString() : value;
  }

  clone(value) {
    if (value === undefined) {
      return undefined;
    }

    return JSON.parse(JSON.stringify(value));
  }
}

Room.STATUS = ROOM_STATUS;
Room.DEFAULT_SETTINGS = DEFAULT_SETTINGS;

module.exports = Room;
